/**
 * @file    app_config.h
 * @brief   应用层总开关。所有"要不要用某个功能"的开关集中在这里，
 *          改一个宏就能切换，不用翻代码。
 *
 * 工程：校赛整合工程（基于 例10_屏幕显示摄像头）
 * 平台：STM32H743VITx + OV2640 + 1.44寸 SPI 屏
 */

#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/* ============================================================
 * 1. 选哪个应用任务跑
 *    1 = 跑你自己的 VisionTask（视觉算法）
 *    0 = 跑例程原来的 CamLcdTask（只显示摄像头画面，用来验硬件）
 *    第一次上板建议先用 0 确认屏幕和摄像头是好的，再切到 1
 * ============================================================ */
#define APP_USE_VISION          1

/* ============================================================
 * 2. 处理区域（ROI）
 *    全图 320x240 每帧都算会很慢，先只看下半部分。
 *    ROI_Y0 = 起始行（0 在最上面），ROI_H = 行数
 *    赛道在画面下半部分，所以从 120 行开始看 120 行
 * ============================================================ */
#define ROI_X0                  0
#define ROI_Y0                  120
#define ROI_W                   320
#define ROI_H                   120

/* ============================================================
 * 3. 扫描行：在 ROI 里挑几行来找边界
 *    值是"相对 ROI 顶部的行号"，数字越大越靠近车头
 * ============================================================ */
#define SCAN_ROW_NEAR           (ROI_H - 10)   /* 近处，找中线主要用这个 */
#define SCAN_ROW_MID            (ROI_H / 2)    /* 中间 */
#define SCAN_ROW_FAR            10             /* 远处，看弯道趋势 */

/* ============================================================
 * 4. 显示开关
 *    1 = 每帧把摄像头画面缩放到屏上（好看，但占 SPI 时间，掉帧）
 *    0 = 屏上只显示帧率等文字（快，调算法时用这个）
 * ============================================================ */
#define APP_SHOW_CAMERA         0

/* ============================================================
 * 5. USB 打印帧率与算法结果
 * ============================================================ */
#define APP_USB_LOG             1

/* ============================================================
 * 6. 图像参数（跟 dcmi_app.h 里保持一致，不要单独改）
 * ============================================================ */
#define IMG_W                   320
#define IMG_H                   240

/* ============================================================
 * 7. 二值化方式
 *    0 = 固定阈值（用 APP_FIXED_THRESHOLD）
 *    1 = Otsu 自动阈值（推荐，第一讲第 5 页）
 * ============================================================ */
#define APP_USE_OTSU            1
#define APP_FIXED_THRESHOLD     157

#endif /* APP_CONFIG_H */
